#!/usr/bin/env node
/**
 * Generates geometric primitive OBJ files for testing.
 * These shapes have known analytical SDFs, making them ideal for
 * validating the mesh-to-SDF pipeline.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = path.join(__dirname, '..', 'public', 'meshes');

function generateSphere(radius, latSegments, lonSegments) {
  const vertices = [];
  const faces = [];

  // Generate vertices
  for (let lat = 0; lat <= latSegments; lat++) {
    const theta = (lat * Math.PI) / latSegments;
    const sinTheta = Math.sin(theta);
    const cosTheta = Math.cos(theta);

    for (let lon = 0; lon <= lonSegments; lon++) {
      const phi = (lon * 2 * Math.PI) / lonSegments;
      const x = radius * sinTheta * Math.cos(phi);
      const y = radius * cosTheta;
      const z = radius * sinTheta * Math.sin(phi);
      vertices.push([x, y, z]);
    }
  }

  // Generate faces
  for (let lat = 0; lat < latSegments; lat++) {
    for (let lon = 0; lon < lonSegments; lon++) {
      const current = lat * (lonSegments + 1) + lon;
      const next = current + lonSegments + 1;

      // Two triangles per quad (1-based for OBJ)
      if (lat !== 0) {
        faces.push([current + 1, next + 1, current + 2]);
      }
      if (lat !== latSegments - 1) {
        faces.push([current + 2, next + 1, next + 2]);
      }
    }
  }

  return { vertices, faces };
}

function generateTorus(majorRadius, minorRadius, majorSegments, minorSegments) {
  const vertices = [];
  const faces = [];

  for (let i = 0; i <= majorSegments; i++) {
    const u = (i * 2 * Math.PI) / majorSegments;
    for (let j = 0; j <= minorSegments; j++) {
      const v = (j * 2 * Math.PI) / minorSegments;
      const x = (majorRadius + minorRadius * Math.cos(v)) * Math.cos(u);
      const y = minorRadius * Math.sin(v);
      const z = (majorRadius + minorRadius * Math.cos(v)) * Math.sin(u);
      vertices.push([x, y, z]);
    }
  }

  for (let i = 0; i < majorSegments; i++) {
    for (let j = 0; j < minorSegments; j++) {
      const current = i * (minorSegments + 1) + j;
      const next = (i + 1) * (minorSegments + 1) + j;
      // 1-based for OBJ
      faces.push([current + 1, next + 1, next + 2]);
      faces.push([current + 1, next + 2, current + 2]);
    }
  }

  return { vertices, faces };
}

function generateCylinder(radius, height, radialSegments, heightSegments) {
  const vertices = [];
  const faces = [];
  const halfHeight = height / 2;

  // Side vertices
  for (let h = 0; h <= heightSegments; h++) {
    const y = -halfHeight + (h * height) / heightSegments;
    for (let r = 0; r < radialSegments; r++) {
      const theta = (r * 2 * Math.PI) / radialSegments;
      const x = radius * Math.cos(theta);
      const z = radius * Math.sin(theta);
      vertices.push([x, y, z]);
    }
  }

  // Side faces
  for (let h = 0; h < heightSegments; h++) {
    for (let r = 0; r < radialSegments; r++) {
      const current = h * radialSegments + r;
      const next = current + radialSegments;
      const currentNext = h * radialSegments + ((r + 1) % radialSegments);
      const nextNext = currentNext + radialSegments;
      // 1-based for OBJ
      faces.push([current + 1, next + 1, nextNext + 1]);
      faces.push([current + 1, nextNext + 1, currentNext + 1]);
    }
  }

  // Top cap center vertex
  const topCenterIdx = vertices.length;
  vertices.push([0, halfHeight, 0]);
  // Bottom cap center vertex
  const bottomCenterIdx = vertices.length;
  vertices.push([0, -halfHeight, 0]);

  // Top cap faces
  const topRingStart = heightSegments * radialSegments;
  for (let r = 0; r < radialSegments; r++) {
    const next = (r + 1) % radialSegments;
    faces.push([topCenterIdx + 1, topRingStart + r + 1, topRingStart + next + 1]);
  }

  // Bottom cap faces
  for (let r = 0; r < radialSegments; r++) {
    const next = (r + 1) % radialSegments;
    faces.push([bottomCenterIdx + 1, next + 1, r + 1]);
  }

  return { vertices, faces };
}

function toOBJ(name, description, geometry) {
  const lines = [];
  lines.push(`# ${name}`);
  lines.push(`# ${description}`);
  lines.push(`# Generated by generate-test-meshes.mjs`);
  lines.push(`# Vertices: ${geometry.vertices.length}, Faces: ${geometry.faces.length}`);
  lines.push('');

  for (const [x, y, z] of geometry.vertices) {
    lines.push(`v ${x.toFixed(6)} ${y.toFixed(6)} ${z.toFixed(6)}`);
  }

  lines.push('');

  for (const face of geometry.faces) {
    lines.push(`f ${face.join(' ')}`);
  }

  lines.push('');
  return lines.join('\n');
}

function toSTL(name, geometry) {
  const lines = [];
  lines.push(`solid ${name}`);

  for (const face of geometry.faces) {
    // Get vertices (face indices are 1-based)
    const v0 = geometry.vertices[face[0] - 1];
    const v1 = geometry.vertices[face[1] - 1];
    const v2 = geometry.vertices[face[2] - 1];

    // Compute face normal
    const e1 = [v1[0] - v0[0], v1[1] - v0[1], v1[2] - v0[2]];
    const e2 = [v2[0] - v0[0], v2[1] - v0[1], v2[2] - v0[2]];
    const nx = e1[1] * e2[2] - e1[2] * e2[1];
    const ny = e1[2] * e2[0] - e1[0] * e2[2];
    const nz = e1[0] * e2[1] - e1[1] * e2[0];
    const len = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;

    lines.push(`  facet normal ${(nx / len).toFixed(6)} ${(ny / len).toFixed(6)} ${(nz / len).toFixed(6)}`);
    lines.push('    outer loop');
    lines.push(`      vertex ${v0[0].toFixed(6)} ${v0[1].toFixed(6)} ${v0[2].toFixed(6)}`);
    lines.push(`      vertex ${v1[0].toFixed(6)} ${v1[1].toFixed(6)} ${v1[2].toFixed(6)}`);
    lines.push(`      vertex ${v2[0].toFixed(6)} ${v2[1].toFixed(6)} ${v2[2].toFixed(6)}`);
    lines.push('    endloop');
    lines.push('  endfacet');
  }

  lines.push(`endsolid ${name}`);
  return lines.join('\n');
}

function toBinarySTL(name, geometry) {
  const numTriangles = geometry.faces.length;
  // 80 byte header + 4 byte triangle count + 50 bytes per triangle
  const bufferSize = 80 + 4 + numTriangles * 50;
  const buffer = Buffer.alloc(bufferSize);

  // Header (80 bytes)
  buffer.write(`Binary STL: ${name}`, 0, 80, 'ascii');

  // Triangle count (uint32)
  buffer.writeUInt32LE(numTriangles, 80);

  let offset = 84;
  for (const face of geometry.faces) {
    const v0 = geometry.vertices[face[0] - 1];
    const v1 = geometry.vertices[face[1] - 1];
    const v2 = geometry.vertices[face[2] - 1];

    // Compute face normal
    const e1 = [v1[0] - v0[0], v1[1] - v0[1], v1[2] - v0[2]];
    const e2 = [v2[0] - v0[0], v2[1] - v0[1], v2[2] - v0[2]];
    const nx = e1[1] * e2[2] - e1[2] * e2[1];
    const ny = e1[2] * e2[0] - e1[0] * e2[2];
    const nz = e1[0] * e2[1] - e1[1] * e2[0];
    const len = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;

    // Normal (3 floats)
    buffer.writeFloatLE(nx / len, offset); offset += 4;
    buffer.writeFloatLE(ny / len, offset); offset += 4;
    buffer.writeFloatLE(nz / len, offset); offset += 4;

    // Vertex 1
    buffer.writeFloatLE(v0[0], offset); offset += 4;
    buffer.writeFloatLE(v0[1], offset); offset += 4;
    buffer.writeFloatLE(v0[2], offset); offset += 4;

    // Vertex 2
    buffer.writeFloatLE(v1[0], offset); offset += 4;
    buffer.writeFloatLE(v1[1], offset); offset += 4;
    buffer.writeFloatLE(v1[2], offset); offset += 4;

    // Vertex 3
    buffer.writeFloatLE(v2[0], offset); offset += 4;
    buffer.writeFloatLE(v2[1], offset); offset += 4;
    buffer.writeFloatLE(v2[2], offset); offset += 4;

    // Attribute byte count (unused)
    buffer.writeUInt16LE(0, offset); offset += 2;
  }

  return buffer;
}

// Generate all meshes
console.log('Generating test meshes...');

const sphere = generateSphere(0.5, 24, 32);
const torus = generateTorus(0.35, 0.15, 32, 16);
const cylinder = generateCylinder(0.5, 1.0, 32, 1);

// Write OBJ files
fs.writeFileSync(
  path.join(OUTPUT_DIR, 'sphere.obj'),
  toOBJ('Unit Sphere', 'Radius 0.5, centered at origin. Analytical SDF: length(p) - 0.5', sphere)
);
console.log(`  sphere.obj: ${sphere.vertices.length} vertices, ${sphere.faces.length} faces`);

fs.writeFileSync(
  path.join(OUTPUT_DIR, 'torus.obj'),
  toOBJ('Torus', 'Major radius 0.35, minor radius 0.15, centered at origin. Analytical SDF: length(vec2(length(p.xz) - 0.35, p.y)) - 0.15', torus)
);
console.log(`  torus.obj: ${torus.vertices.length} vertices, ${torus.faces.length} faces`);

fs.writeFileSync(
  path.join(OUTPUT_DIR, 'cylinder.obj'),
  toOBJ('Cylinder', 'Radius 0.5, height 1.0, centered at origin. Analytical SDF: max(length(p.xz) - 0.5, abs(p.y) - 0.5)', cylinder)
);
console.log(`  cylinder.obj: ${cylinder.vertices.length} vertices, ${cylinder.faces.length} faces`);

// Write ASCII STL of the sphere
fs.writeFileSync(
  path.join(OUTPUT_DIR, 'sphere.stl'),
  toSTL('sphere', sphere)
);
console.log(`  sphere.stl: ASCII STL, ${sphere.faces.length} triangles`);

// Write binary STL of the cylinder
fs.writeFileSync(
  path.join(OUTPUT_DIR, 'cylinder.stl'),
  toBinarySTL('cylinder', cylinder)
);
console.log(`  cylinder.stl: Binary STL, ${cylinder.faces.length} triangles`);

console.log('Done!');
